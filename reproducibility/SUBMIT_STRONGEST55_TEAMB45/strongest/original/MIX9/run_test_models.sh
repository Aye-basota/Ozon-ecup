#!/usr/bin/env bash
# MIX9 — тестовые модели `SEQ-01` для сидов 43 и 44, глубина ОБРЕЗАНА до 289.
# Запускать НА СЕРВЕРЕ из /root/ecup после `setup_server.sh`.
#
# Зачем это вообще нужно. Кандидат смеси — `SEQ-AVG3 @ clip289`, то есть
# лог-среднее трёх сидов. Тестовый прогноз сида 42 с обрезкой уже есть
# (`artifacts/ztest_SEQ-01.npy`, он внутри отправленного чемпиона `SEQ-01-MIX`),
# а сиды 43/44 существуют ТОЛЬКО на полной глубине (`ztest_SEQ-S4?-FULL.npy`,
# `exp_026`): тестовые веса тогда не сохранялись, и пересчитать обрезку 40
# секундами инференса нельзя — модели нет. Поэтому здесь они обучаются заново
# тем же рецептом. `exp_027` эту дыру закрыл: `predict` теперь всегда пишет
# `artifacts/model_<EXP>-TEST.pt`, так что второй раз этой цены не будет.
#
# Рецепт СОВПАДАЕТ с `SEQ/run.sh` (сид 42, чемпион): 29 обучающих cutoff'ов
# всего чистого коридора, 4 эпохи, `--depth-clip 289`. Отличие только `--seed`.
# `--compile` — как у `SEQ2/run.sh`, где считались сами сиды 43/44.
#
# ВАЖНО: имя эксперимента НЕ `SEQ-S43`, чтобы не затереть `ztest_SEQ-S43-FULL.npy`
# из `exp_026` — это артефакт провалившегося на LB сабмита, и он нужен как улика.
#
# Цена: 29 cutoff'ов x 4 эпохи на A10 с `--compile` ~ 36 мин на модель,
# то есть ~75 мин на обе последовательно на одной карте. При двух картах —
# по одному сиду на карту, ~40 мин.
set -u
cd /root/ecup
export PYTHONIOENCODING=utf-8
L=artifacts
SEEDS=${SEEDS:-"43 44"}

for S in $SEEDS; do
  EXP="SEQ-C289-S$S"
  if [ -f "$L/ztest_${EXP}.npy" ]; then echo "== ПРОПУСК $EXP: ztest уже есть"; continue; fi
  echo "== СТАРТ $EXP $(date -u '+%F %T')"
  python3 -m src.seq predict --exp "$EXP" --seed "$S" --epochs 4 \
      --depth-clip 289 --compile > "$L/MIX9_${EXP}.log" 2>&1
  echo "== ГОТОВО $EXP $(date -u '+%F %T') rc=$?"
  tail -n 8 "$L/MIX9_${EXP}.log"
done
echo "== MIX9 ALL_DONE $(date -u '+%F %T')"
