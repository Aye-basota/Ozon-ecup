#!/usr/bin/env bash
# EXP-038 (FNL) — КОНТРОЛЬ ШУМА: повтор BASE тем же сидом в другом процессе.
#
# Зачем. Дельта арки к BASE меряется между ДВУМЯ ПРОЦЕССАМИ, а рецепт проекта
# держит `cudnn.benchmark = True` + TF32 + bf16 и не включает
# `use_deterministic_algorithms`, поэтому один и тот же сид на одной и той же
# карте не даёт побитово одного и того же обучения: опубликованный
# `SEQ-D3A-S42` на фолде 10-16 дал калиброванный 1.74637 (`exp_030`, та же
# локальная 4060 Ti, 4 эпохи, сид 42), а свежий `FNL-BASE-L00-S42` того же
# рецепта — 1.74713, то есть +0.00076 при нулевом изменении постановки.
#
# Внутри одного процесса всё детерминировано — это проверено побитово
# (`test_lambda_zero_is_bitwise_the_base_run`). Значит источник разброса —
# именно межпроцессный, и именно он ограничивает разрешающую способность
# гейта: полоса REJECT |FUNNEL − BUYCTRL| <= 0.0005 лежит примерно на этом
# уровне.
#
# `FNL-BASE-R2` — повтор BASE с тем же сидом и тем же кодом. Новой информации в
# нём нет по построению, поэтому его дельта к `FNL-BASE` есть ЦЕНА САМОГО
# ПРОГОНА: та же роль, что у контроля `SELF` в `exp_024` и у перемешанной `rho`
# в `exp_021`. Любая дельта арки, не превосходящая её, — не результат.
#
# Запускать ПОСЛЕ основной очереди (`run.sh`), чтобы не задерживать главную пару.
set -u
cd "$(dirname "$0")/../../../.."
export PYTHONIOENCODING=utf-8
L=artifacts
V=2025-10-16
EPOCHS=4
SEED=42
exp=FNL-BASER2-L00-S42
tag="${exp}-V1016"

if [ -f "$L/oof_${tag}.npz" ]; then
  echo "== ПРОПУСК ${tag}: OOF уже есть"
else
  echo "== СТАРТ ${tag} (контроль шума прогона) $(date '+%F %T')"
  python -m src.fnl fold --val "$V" --arm BASE --lam 0 --exp "$exp" \
      --epochs "$EPOCHS" --seed "$SEED" --depth-aug 0.5 --curve \
      > "$L/FNL1_${tag}.log" 2>&1
  rc=$?
  if ! grep -q "эпоха ${EPOCHS}/${EPOCHS}" "$L/FNL1_${tag}.log"; then
    echo "!! РЕЦЕПТ ${tag}: в логе нет «эпоха ${EPOCHS}/${EPOCHS}» — прогон невалиден"
  fi
  echo "== ГОТОВО ${tag} rc=${rc} $(date '+%F %T')"
  tail -n 8 "$L/FNL1_${tag}.log"
fi
echo "== FNL1 CTRL_DONE $(date '+%F %T')"
